// -----------------------------------------------------------------------
// Architecture diagram lightbox: click any diagram (or press Enter/Space
// on it) to expand it full-screen; Escape, the backdrop, or the close
// button dismiss it. One lightbox serves every diagram on the page.
// -----------------------------------------------------------------------
(function () {
  var triggers = document.querySelectorAll('.arch-diagram-trigger');
  var lightbox = document.getElementById('arch-diagram-lightbox');
  var closeBtn = document.getElementById('arch-diagram-lightbox-close');
  var img = document.getElementById('arch-diagram-lightbox-img');
  if (!triggers.length || !lightbox || !closeBtn || !img) return;
  var lastTrigger = null;

  function openLightbox(trigger) {
    lastTrigger = trigger;
    img.src = trigger.getAttribute('data-diagram');
    img.alt = trigger.getAttribute('data-diagram-alt') + ', expanded';
    img.width = trigger.getAttribute('data-diagram-width');
    img.height = trigger.getAttribute('data-diagram-height');
    lightbox.classList.add('is-open');
    lightbox.setAttribute('aria-hidden', 'false');
    document.body.classList.add('diagram-lightbox-open');
    closeBtn.focus();
  }

  function closeLightbox() {
    lightbox.classList.remove('is-open');
    lightbox.setAttribute('aria-hidden', 'true');
    document.body.classList.remove('diagram-lightbox-open');
    if (lastTrigger) lastTrigger.focus();
  }

  triggers.forEach(function (trigger) {
    trigger.addEventListener('click', function () { openLightbox(trigger); });
  });
  closeBtn.addEventListener('click', closeLightbox);
  lightbox.addEventListener('click', function (event) {
    if (event.target === lightbox) closeLightbox();
  });
  document.addEventListener('keydown', function (event) {
    if (event.key === 'Escape' && lightbox.classList.contains('is-open')) {
      closeLightbox();
    }
  });
})();

